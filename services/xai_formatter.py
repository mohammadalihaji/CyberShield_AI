# Mapping of analysis types to their dedicated formatters.
_FORMATTERS = {
    "website": format_website_report,
    "email": format_email_report,
    "image": format_image_report,
    "password": format_password_report,
    "advisor": format_advisor_report,
}


def format_report(data: Dict[str, Any], analysis_type: Optional[str] = None) -> str:
    """
    Converts a structured analysis dictionary into a clean, professional
    XAI markdown report.

    Auto-dispatches to the module-specific formatter based on
    analysis_type. Falls back to the generic formatter if no match.

    If the data already contains an 'explanation_markdown' field, it is
    preserved as a fallback — but the formatter's output takes priority
    to ensure consistency.

    Args:
        data: The validated analysis dictionary from the response parser.
        analysis_type: Optional override for the analysis type.
            If not provided, the value of data['analysis_type'] is used.

    Returns:
        A markdown-formatted XAI report string.
    """
    if not data or not isinstance(data, dict):
        logger.warning("XAI formatter received invalid data; returning fallback.")
        return format_generic_report({})

    # Determine the analysis type.
    atype = (analysis_type or data.get("analysis_type") or "").lower().strip()

    formatter = _FORMATTERS.get(atype)
    if formatter:
        try:
            return formatter(data)
        except Exception as exc:
            logger.error("XAI formatter error for type '%s': %s", atype, exc)
            return format_generic_report(data)

    return format_generic_report(data)

