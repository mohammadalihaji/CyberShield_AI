"""
Explainable AI (XAI) Formatter for CyberShield AI.

Purpose:
    Converts structured analysis dictionaries (produced by the response parser)
    into consistent, professional XAI markdown reports that are short, clear
    and easy for everyday users to understand.

    The layout mirrors the classic CyberShield report style described in the
    original `gemini_service.py`:

        Website / Image :  ### 🛡️ Explainable AI (XAI) Assessment:
        Email           :  ### 📧 Security Assessment: <risk_level>
        Password        :  ### 🔑 Strength Report: <risk_level>
        Advisor         :  ### 🛡️ Cyber Shield Security Advisor Summary

    Each report uses 2-5 short scannable bullet points with bold labels, and
    image reports include a short plain-language "Visual Analysis Details"
    paragraph. This produces clean, commercial-product output instead of a
    generic chatbot monologue.

Public methods:
    format_report(data, analysis_type)          -> str  (auto-dispatch)
    format_website_report(data)                 -> str
    format_email_report(data)                   -> str
    format_image_report(data)                   -> str
    format_password_report(data)                -> str
    format_advisor_report(data)                 -> str
    format_generic_report(data)                 -> str  (fallback)
"""

from typing import Any, Dict, List, Optional

from utils.logger import get_logger

logger = get_logger(__name__)


# ---------------------------------------------------------------------------
# Shared helpers
# ---------------------------------------------------------------------------

def _safe_str(value: Any, default: str = "N/A") -> str:
    """Returns a safe string representation of a value."""
    if value is None:
        return default
    if isinstance(value, bool):
        return "Yes" if value else "No"
    if isinstance(value, float):
        return f"{value:.2f}"
    return str(value)


def _safe_list(value: Any) -> List[str]:
    """Ensures the value is a list of strings."""
    if not value:
        return []
    if isinstance(value, list):
        return [str(item) for item in value if item]
    if isinstance(value, str):
        return [value]
    return [str(value)]


def _bullet(items: Optional[List[str]], default: str = "No data available.") -> str:
    """Formats a list of strings as simple markdown bullets."""
    items = _safe_list(items)
    if not items:
        return f"* {default}\n"
    return "".join(f"* {item}\n" for item in items)


def _kv_bullets(pairs: Dict[str, Any]) -> str:
    """Formats key/value pairs as classic bold-label bullets: '* **Label**: value'."""
    if not pairs:
        return "* No data available.\n"
    return "\n".join(
        f"* **{key.replace('_', ' ').title()}**: {_safe_str(value)}"
        for key, value in pairs.items()
    ) + "\n"


