def format_website_report(data: Dict[str, Any]) -> str:
    """
    Builds a classic short XAI report for website / URL analysis.
    """
    risk_level = _safe_str(data.get("risk_level"), "Unknown")
    summary = _safe_str(data.get("summary"), "No summary available.")
    reasoning = _safe_list(data.get("reasoning"))
    recommendations = _safe_list(data.get("recommendations"))
    limitations = _safe_list(data.get("limitations"))

    malware_found = data.get("malware_found")
    malware_label = "No malware signatures flagged" if not malware_found else "Malware indicators detected"

    report = "### 🛡️ Explainable AI (XAI) Assessment:\n\n"
    report += f"* **Risk Level**: {risk_level}.\n"
    report += f"* **Malware Detection**: {malware_label}.\n\n"

    if reasoning:
        report += "**Why This Assessment:**\n" + _bullet(reasoning) + "\n"

    report += "**Recommendation:**\n" + _bullet(recommendations, "No specific recommendation available.") + "\n"

    if limitations:
        report += "**Limitations:**\n" + _bullet(limitations) + "\n"

    if summary and summary != "No summary available.":
        report += f"*Summary: {summary}*\n"

    report += "\n_Report generated by CyberShield AI Explainable Analysis Engine._\n"
    return report


def format_email_report(data: Dict[str, Any]) -> str:
    """
    Builds a classic short XAI report for email phishing analysis.

    Header: ### 📧 Security Assessment: <risk_level>
    """
    risk_level = _safe_str(data.get("risk_level"), "Unknown")
    confidence = _safe_str(data.get("confidence"), "0")
    summary = _safe_str(data.get("summary"), "No summary available.")
    reasoning = _safe_list(data.get("reasoning"))
    recommendations = _safe_list(data.get("recommendations"))
    limitations = _safe_list(data.get("limitations"))

    spoofed = data.get("spoofed_domain")
    spoof_label = "Sender address does not match the legitimate brand domain" if spoofed else "No domain spoofing detected"
    phishing_score = data.get("phishing_score")

    report = f"### 📧 Security Assessment: {risk_level}\n\n"
    report += f"* **Phishing Score**: {_safe_str(phishing_score) if phishing_score is not None else 'N/A'}% — probability of fraudulent mail.\n"
    report += f"* **Spoofing Check**: {spoof_label}.\n"
    report += f"* **Urgency Language**: {_safe_str(data.get('urgency'), 'Normal')} urgency signals detected in the message body.\n"
    report += f"* **Social Engineering**: {_safe_str(data.get('social_engineering'), 'Not Assessed')}.\n"
    report += f"* **Suspicious Links**: {_safe_str(data.get('suspicious_links'), '0')} hyperlink reference(s) found in the content.\n"
    report += f"* **SPF Check**: {_safe_str(data.get('spf_check'), 'Not Available')}; DKIM: {_safe_str(data.get('dkim_check'), 'Not Available')}; DMARC: {_safe_str(data.get('dmarc_check'), 'Not Available')}.\n\n"

    if reasoning:
        report += "**Why This Assessment:**\n" + _bullet(reasoning) + "\n"

    report += "**Recommendation:**\n" + _bullet(recommendations, "No specific recommendation available.") + "\n"

    if limitations:
        report += "**Limitations:**\n" + _bullet(limitations) + "\n"

    if summary and summary != "No summary available.":
        report += f"*Summary: {summary}*\n"

    report += "\n_Report generated by CyberShield AI Explainable Analysis Engine._\n"
    return report


def format_image_report(data: Dict[str, Any]) -> str:
    """
    Builds a classic short XAI report for image authenticity analysis.

    Header: ### 🛡️ Explainable AI (XAI) Assessment:
    Then 2-3 short bullets + a "Visual Analysis Details" paragraph.
    """
    risk_level = _safe_str(data.get("risk_level"), "Unknown")
    confidence = _safe_str(data.get("confidence"), "0")
    summary = _safe_str(data.get("summary"), "No summary available.")
    reasoning = _safe_list(data.get("reasoning"))
    recommendations = _safe_list(data.get("recommendations"))
    limitations = _safe_list(data.get("limitations"))

    ai_prob = data.get("ai_probability", data.get("ai_confidence"))
    ai_prob_label = f"{_safe_str(ai_prob)}%" if ai_prob is not None else "N/A"

    report = "### 🛡️ Explainable AI (XAI) Assessment:\n\n"
    report += f"* **Risk Classification**: {risk_level} (confidence {confidence}%).\n"
    report += f"* **AI Probability**: {ai_prob_label} chance the image is AI-generated or digitally manipulated.\n"

    # Short forensic clues (2-3 bullets).
    forensic_clues = []
    if reasoning:
        forensic_clues = reasoning[:3]
    elif data.get("gan_artifacts"):
        forensic_clues.append(f"GAN Artifacts: {data.get('gan_artifacts')}.")
    if data.get("noise") or data.get("noise_score"):
        forensic_clues.append(f"Noise Analysis: {_safe_str(data.get('noise') or data.get('noise_score'))}.")
    if data.get("lighting_consistency") or data.get("lighting"):
        forensic_clues.append(f"Lighting Consistency: {_safe_str(data.get('lighting_consistency') or data.get('lighting'))}.")
    if data.get("pixel_irregularity"):
        forensic_clues.append(f"Pixel Irregularity: {data.get('pixel_irregularity')}.")
    if data.get("compression_analysis"):
        forensic_clues.append(f"Compression Analysis: {data.get('compression_analysis')}.")

    if forensic_clues:
        for clue in forensic_clues[:3]:
            report += f"* **Forensic Clue**: {clue}\n"
    report += "\n"

    # Plain-language visual analysis paragraph (classic style).
    if risk_level.lower() in ("unsafe", "malicious", "suspicious", "fake", "ai-generated"):
        verdict_desc = "synthetic generation or digital manipulation"
    else:
        verdict_desc = "authentic, natural photography"

    report += "**Visual Analysis Details:**\n"
    if summary and summary != "No summary available.":
        report += f"{summary} "
    report += (
        f"The forensic evidence points toward {verdict_desc}. "
        "Generative models and editing tools commonly leave detectable traces in "
        "noise distribution, lighting coherence, and edge/texture micro-patterns. "
        "Review the specific indicators above before making a final determination.\n\n"
    )

    report += "**Recommendation:**\n" + _bullet(recommendations, "No specific recommendation available.") + "\n"

    if limitations:
        report += "**Limitations:**\n" + _bullet(limitations) + "\n"

    report += "\n_Report generated by CyberShield AI Explainable Forensic Engine._\n"
    return report


def format_password_report(data: Dict[str, Any]) -> str:
    """
    Builds a classic short XAI report for password strength analysis.

    Header: ### 🔑 Strength Report: <risk_level>
    """
    risk_level = _safe_str(data.get("risk_level"), "Unknown")
    confidence = _safe_str(data.get("confidence"), "0")
    summary = _safe_str(data.get("summary"), "No summary available.")
    reasoning = _safe_list(data.get("reasoning"))
    recommendations = _safe_list(data.get("recommendations"))
    limitations = _safe_list(data.get("limitations"))

    pwned = data.get("pwned_count", 0)
    breach_label = (
        f"⚠️ Flagged {pwned} time(s) in known breach databases" if pwned and pwned > 0
        else "✅ No immediate breach records matching this profile"
    )
    entropy = data.get("entropy")

    report = f"### 🔑 Strength Report: {risk_level}\n\n"
    if entropy is not None:
        report += f"* **Entropy Rating**: **{_safe_str(entropy)} bits** — passwords should ideally exceed 60 bits to resist GPU brute force.\n"
    report += f"* **Length Check**: Found {_safe_str(data.get('length'))} characters; optimal length is 16+ characters.\n"
    report += f"* **Breach Database**: {breach_label}.\n"
    report += f"* **Dictionary Risk**: {_safe_str(data.get('dictionary_risk'), 'Not Assessed')}.\n"
    report += f"* **Pattern Detection**: {_safe_str(data.get('pattern_detection'), 'None Detected')}.\n"
    report += f"* **Estimated Crack Time**: {_safe_str(data.get('estimated_crack_time'), 'N/A')}.\n"
    report += (
        "* **Character Variety**: "
        f"Uppercase {'✓' if data.get('has_uppercase') else '✗'} | "
        f"Lowercase {'✓' if data.get('has_lowercase') else '✗'} | "
        f"Digits {'✓' if data.get('has_digit') else '✗'} | "
        f"Symbols {'✓' if data.get('has_special') else '✗'}.\n\n"
    )

    if reasoning:
        report += "**Why This Assessment:**\n" + _bullet(reasoning) + "\n"

    report += "**Action Steps:**\n" + _bullet(recommendations, "No specific recommendation available.") + "\n"

    if limitations:
        report += "**Limitations:**\n" + _bullet(limitations) + "\n"

    if summary and summary != "No summary available.":
        report += f"*Summary: {summary}*\n"

    report += "\n_Report generated by CyberShield AI Explainable Analysis Engine._\n"
    return report


def format_advisor_report(data: Dict[str, Any]) -> str:
    """
    Builds a classic short XAI report for the security posture advisor.

    Header: ### 🛡️ Cyber Shield Security Advisor Summary
    Includes health score, key profile statistics, and immediate action items.
    """
    risk_level = _safe_str(data.get("risk_level"), "Unknown")
    overall_score = data.get("overall_score", "N/A")
    summary = _safe_str(data.get("summary"), "No summary available.")
    reasoning = _safe_list(data.get("reasoning"))
    limitations = _safe_list(data.get("limitations"))

    report = "### 🛡️ Cyber Shield Security Advisor Summary\n\n"
    report += f"Based on your profile, your Cyber Security Health Score is **{_safe_str(overall_score)}/100** "
    report += f"(overall risk: **{risk_level}**).\n\n"

    if summary and summary != "No summary available.":
        report += f"{summary}\n\n"

    raw_recs = data.get("recommendations", [])

    # Structured recommendation objects (title / priority / action_steps / reason).
    if raw_recs and isinstance(raw_recs[0], dict):
        report += "#### 🚩 Immediate Action Items:\n\n"
        for idx, rec in enumerate(raw_recs, start=1):
            title = rec.get("title", f"Priority {idx}")
            priority = rec.get("priority", "Medium")
            category = rec.get("category", "General")
            steps = rec.get("action_steps", "No steps provided.")
            reason = rec.get("reason", "")
            report += f"**{idx}. {title}** (Priority: {priority} | Category: {category})\n"
            report += f"* **Action Steps**: {steps}\n"
            if reason:
                report += f"* **Why It Helps**: {reason}\n"
            report += "\n"
    else:
        recs = _safe_list(raw_recs)
        if recs:
            report += "#### 🚩 Immediate Action Items:\n\n"
            for idx, rec in enumerate(recs[:5], start=1):
                report += f"{idx}. {rec}\n"
            report += "\n"

    if reasoning:
        report += "**Why This Assessment:**\n" + _bullet(reasoning) + "\n"

    if limitations:
        report += "**Limitations:**\n" + _bullet(limitations) + "\n"

    report += "\n_Report generated by CyberShield AI Explainable Analysis Engine._\n"
    return report


